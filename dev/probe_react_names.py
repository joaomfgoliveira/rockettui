#!/usr/bin/env python3
"""Probe which emoji shortcodes the server accepts for reactions (change add-reaction-picker).

Usage (from the repository root):
    EMOJI_DUMP=/tmp/emoji.tsv cargo test --lib dump_crate_shortcodes -- --ignored
    # optional: other names the server's own emoji data gives each emoji (see dev/emoji_alternates.py)
    python3 -I dev/emoji_alternates.py /tmp/emoji.tsv <emojibase shortcodes dir> > /tmp/alts.tsv
    python3 -I dev/probe_react_names.py /tmp/emoji.tsv [--alts /tmp/alts.tsv] [src/ui/emoji_names/data.rs]

Skin tones (change add-emoji-box-grid): the server's name for a toned emoji is `<name>_tone<N>`,
N in 1..5, and whether every toned emoji has an accepted name is a fact about the server too.
    EMOJI_TONES=/tmp/tones.tsv cargo test --lib dump_toned_names -- --ignored
    python3 -I dev/probe_react_names.py --tones /tmp/tones.tsv [src/ui/emoji_names/tone_data.rs]
Each line of the tones dump is the emoji's first shortcode and the name that is sent for it. The
probe reacts with each of the five toned names and lists, by first shortcode, the emoji for which
any of them is refused; the picker offers those without a tone.

Standard library only. Runs against the throwaway local server that dev/seed.py started. The
picker finds unicode emoji with the `emojis` crate (GitHub's shortcodes), but the server has its
own set and answers 400 to a name it does not know. For every emoji of the dump (one line: the
glyph, then tab-separated shortcodes, the first of which is the emoji's id) the probe posts
`chat.react` as the app user with each shortcode in turn until one is accepted, then takes the
reaction back. With `--alts`, names from the alternates file (one line: the emoji id, then other
names to try) are tried after the crate's own. It records:
  * emoji whose first shortcode is accepted: nothing to store;
  * emoji whose first shortcode is rejected but another is accepted: `(first, accepted)`;
  * emoji with no accepted shortcode: the picker will not offer them.

The REST rate limiter would throttle thousands of calls, so it is turned off as admin
(`API_Enable_Rate_Limiter`) and put back in a `finally`; the last lines say whether it is back.
Output rule: every line holds only counts and a verdict. The shortcode lists go only to the
generated file. Nothing printed holds a credential, a message text or a response body. The server
must be on loopback: this script changes a setting and must never touch the company server.

The last line is `PROBE OK` only when the setting is back to its original value, the throwaway
message was deleted and no call failed in a way that is not a plain refusal.
"""

import importlib.util
import os
import sys
import time
import urllib.parse

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIMITER = "API_Enable_Rate_Limiter"


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


cap = load("capture_reactions", os.path.join(REPO, "dev", "capture_reactions.py"))
pe = cap.pe


def read_dump(path):
    """`[(glyph, [shortcode, ...]), ...]` from the dump of the `emojis` crate."""
    with open(path, encoding="utf-8") as handle:
        rows = [line.rstrip("\n").split("\t") for line in handle if line.strip()]
    return [(row[0], row[1:]) for row in rows]


def read_alts(path):
    """`{first shortcode: [other name, ...]}`."""
    with open(path, encoding="utf-8") as handle:
        rows = [line.rstrip("\n").split("\t") for line in handle if line.strip()]
    return {row[0]: row[1:] for row in rows}


def write_data(path, send_as, unsendable, total, server):
    def quoted(text):
        return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')

    lines = [
        "//! Generated by `dev/probe_react_names.py` against a real server. Do not edit by hand: run the",
        "//! probe again.",
        "//!",
        "//! Probed %d emoji against %s." % (total, server),
        "",
        "/// Emoji whose first shortcode the server rejects but another of its shortcodes it accepts:",
        "/// `(first shortcode, shortcode to send)`.",
        "pub const SEND_AS: &[(&str, &str)] = &[",
    ]
    lines += ["    (%s, %s)," % (quoted(a), quoted(b)) for a, b in sorted(send_as)]
    lines += [
        "];",
        "",
        "/// Emoji, by first shortcode, for which the server accepts none of the shortcodes the crate knows.",
        "pub const UNSENDABLE: &[&str] = &[",
    ]
    lines += ["    %s," % quoted(first) for first in sorted(unsendable)]
    lines += ["];", ""]
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def read_tones(path):
    """`[(first shortcode, name that is sent), ...]` from the dump of toned emoji."""
    with open(path, encoding="utf-8") as handle:
        rows = [line.rstrip("\n").split("\t") for line in handle if line.strip()]
    return [(row[0], row[1]) for row in rows if len(row) >= 2]


def write_tone_data(path, refused, total, server):
    lines = [
        "//! Generated by `dev/probe_react_names.py --tones` against a real server. Do not edit by hand: run",
        "//! the probe again.",
        "//!",
        "//! Probed %d emoji with skin tones against %s." % (total, server),
        "",
        "/// Emoji, by first shortcode, for which the server refuses at least one of `<name>_tone1..5`: the",
        "/// picker offers them without a tone.",
        "pub const TONE_REFUSED: &[&str] = &[",
    ]
    lines += ['    "%s",' % first.replace("\\", "\\\\").replace('"', '\\"') for first in sorted(refused)]
    lines += ["];", ""]
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def probe_tones(app, dev, admin, original, server, room, tones, out_path):
    """React with `<name>_tone1..5` for every toned emoji; list the ones with a refused name."""
    mid = None
    clean = True
    refused = []
    started = time.time()
    try:
        pe.out("rate limiter was %s, turning it off: %s" % (original, "ok" if pe.set_setting(admin, LIMITER, False) else "FAILED"))
        mid = pe.post_message(dev, room, "react tones probe")
        for index, (first, sent) in enumerate(tones, 1):
            for tone in range(1, 6):
                name = ":%s_tone%d:" % (sent, tone)
                result = cap.react(dev, mid, name, True)
                if result == 200:
                    cap.react(dev, mid, name, False)
                    continue
                if result == 400:
                    refused.append(first)
                    break
                pe.out("PROBE STOP: unexpected status %d at emoji %d" % (result, index))
                clean = False
                break
            if not clean:
                break
            if index % 100 == 0:
                pe.out("probed %d/%d (%ds)" % (index, len(tones), time.time() - started))
    finally:
        if mid:
            pe.api("POST", "/api/v1/chat.delete", {"roomId": room, "msgId": mid}, dev)
        pe.set_setting(admin, LIMITER, original)
        back = pe.get_setting(admin, LIMITER)
        pe.out("rate limiter restored: %s" % ("yes" if back == original else "NO (set %s by hand)" % LIMITER))
        restored = back == original
    pe.out("toned emoji probed=%d with a refused tone=%d" % (len(tones), len(refused)))
    if out_path and clean:
        write_tone_data(out_path, refused, len(tones), server)
        pe.out("wrote %s" % out_path)
    ok = clean and restored
    pe.out("PROBE OK" if ok else "PROBE FAIL")
    return 0 if ok else 1


def main(argv):
    args = argv[1:]
    tones = None
    if "--tones" in args:
        at = args.index("--tones")
        tones = read_tones(args[at + 1])
        del args[at : at + 2]
    alts = {}
    if "--alts" in args:
        at = args.index("--alts")
        alts = read_alts(args[at + 1])
        del args[at : at + 2]
    if tones is None and not args:
        print("usage: probe_react_names.py <emoji.tsv> [--alts alts.tsv] [out.rs]")
        print("       probe_react_names.py --tones <tones.tsv> [out.rs]")
        return 2
    if tones is None:
        dump = [codes for _glyph, codes in read_dump(args[0])]
        out_path = args[1] if len(args) > 1 else None
    else:
        dump = []
        out_path = args[0] if args else None
    try:
        app = pe.read_env(pe.APP_ENV)
        env = pe.read_env(pe.ADMIN_ENV)
        pe.BASE = app["ROCKETTUI_SERVER_URL"].rstrip("/")
        dev = (app["ROCKETTUI_USER_ID"], app["ROCKETTUI_TOKEN"])
        admin_pass = env["ADMIN_PASS"]
    except (OSError, KeyError):
        print("PROBE FAIL: no dev state files; run dev/seed.py up and seed first")
        return 1
    pe.SECRETS.update(v for v in (dev[0], dev[1], admin_pass) if v)
    if urllib.parse.urlparse(pe.BASE).hostname not in pe.LOOPBACK:
        pe.out("PROBE FAIL: not a loopback server")
        return 1

    admin = pe.login("admin", admin_pass)
    original = pe.get_setting(admin, LIMITER)
    if original is None:
        pe.out("PROBE FAIL: the rate limiter setting could not be read, so it could not be restored")
        return 1
    status, info = pe.api("GET", "/api/info")
    server = "Rocket.Chat %s" % ((info or {}).get("version", "unknown") if isinstance(info, dict) else "unknown")

    status, subs = pe.api("GET", "/api/v1/subscriptions.get", auth=dev)
    room = next((s["rid"] for s in (subs or {}).get("update", []) if s.get("name") == "rt-public"), None)
    if status != 200 or not room:
        pe.out("PROBE FAIL: rt-public not found")
        return 1

    if tones is not None:
        return probe_tones(app, dev, admin, original, server, room, tones, out_path)

    mid = None
    clean = True
    first_ok = 0
    send_as = []
    unsendable = []
    started = time.time()
    try:
        pe.out("rate limiter was %s, turning it off: %s" % (original, "ok" if pe.set_setting(admin, LIMITER, False) else "FAILED"))
        mid = pe.post_message(dev, room, "react names probe")
        for index, codes in enumerate(dump, 1):
            accepted = None
            tried = codes + [n for n in alts.get(codes[0], []) if n not in codes]
            for code in tried:
                result = cap.react(dev, mid, ":%s:" % code, True)
                if result == 200:
                    cap.react(dev, mid, ":%s:" % code, False)
                    accepted = code
                    break
                if result == 400:
                    continue
                # Anything else is not a plain refusal: throttled, down or an unexpected answer.
                pe.out("PROBE STOP: unexpected status %d at emoji %d" % (result, index))
                clean = False
                break
            if not clean:
                break
            if accepted == codes[0]:
                first_ok += 1
            elif accepted is not None:
                send_as.append((codes[0], accepted))
            else:
                unsendable.append(codes[0])
            if index % 300 == 0:
                pe.out("probed %d/%d (%ds)" % (index, len(dump), time.time() - started))
    finally:
        if mid:
            pe.api("POST", "/api/v1/chat.delete", {"roomId": room, "msgId": mid}, dev)
        pe.set_setting(admin, LIMITER, original)
        back = pe.get_setting(admin, LIMITER)
        pe.out("rate limiter restored: %s" % ("yes" if back == original else "NO (set %s by hand)" % LIMITER))
        restored = back == original

    total = len(dump)
    pe.out(
        "emoji probed=%d first shortcode accepted=%d renamed=%d unsendable=%d"
        % (total, first_ok, len(send_as), len(unsendable))
    )
    if out_path and clean:
        write_data(out_path, send_as, unsendable, total, server)
        pe.out("wrote %s" % os.path.relpath(out_path, REPO) if os.path.isabs(out_path) else "wrote %s" % out_path)
    ok = clean and restored and first_ok + len(send_as) + len(unsendable) == total
    pe.out("PROBE OK" if ok else "PROBE FAIL")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
